TEXTE_CONTRACTION = """Les nations se donnent des héros, et les écrivains sont priés de les mettre en scène. L'exercice paraît simple ; il est en réalité l'un des plus difficiles qui soient, car deux exigences y entrent aussitôt en conflit. La mémoire collective demande une figure stable, reconnaissable, exemplaire. La littérature, elle, ne vit que de ce qui bouge, hésite et se contredit.

Le premier écueil est l'hagiographie. Un texte qui admire sans réserve cesse d'informer : il confirme. Le lecteur y retrouve ce qu'il savait déjà, applaudit, et referme le livre exactement là où il l'avait ouvert. Rien ne s'est passé. Une œuvre, au contraire, doit laisser son lecteur légèrement déplacé, et ce déplacement suppose qu'on lui ait montré quelque chose qu'il n'avait pas prévu.

Le second écueil tient à l'adversaire. Pour que le héros soit grand, il est tentant de rendre son ennemi méprisable. Mais un adversaire sans arguments ne fait pas un conflit, il fait une démonstration. Les œuvres qui durent sont celles où l'on comprend, un instant au moins, comment l'autre camp pouvait se croire dans son droit. Cela ne revient pas à l'excuser : cela revient à mesurer ce qu'il a fallu de force pour lui résister.

Le troisième écueil est le plus subtil : c'est celui de la nécessité. Si le héros ne pouvait pas agir autrement, il n'a rien décidé, et son courage se réduit à un tempérament. Il faut donc, pour qu'une figure exemplaire reste vivante, lui ménager une porte de sortie qu'elle refusera d'emprunter. Le refus n'a de valeur que devant une possibilité réelle.

On objectera que ces précautions d'écrivain sont un luxe, et que les peuples récemment sortis de la domination ont d'abord besoin de figures fondatrices, non de nuances. L'objection mérite considération : il est des moments où une nation a besoin qu'on lui raconte simplement d'où elle vient, et l'on ne reprochera pas à un auteur d'y avoir contribué.

Reste que la simplicité ne se transmet pas. Une figure sans faille lasse à la deuxième génération, tandis qu'un personnage qui doute continue d'être joué. Le meilleur service qu'un écrivain puisse rendre à un héros national n'est donc pas de le rendre irréprochable, mais de le rendre disputable — car seul ce qui se discute continue d'être lu."""
