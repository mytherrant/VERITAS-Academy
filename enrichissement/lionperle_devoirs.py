TEXTE_CONTRACTION = """On répète volontiers que le théâtre africain d'expression française ou anglaise aurait eu pour première tâche de défendre la tradition contre l'agression coloniale. La formule est commode, et elle est fausse dès qu'on ouvre les textes. Les dramaturges qui comptent n'ont pas écrit des plaidoyers : ils ont écrit des pièces, c'est-à-dire des machines à montrer que personne n'a entièrement raison.

La confusion vient d'un malentendu sur ce qu'est un personnage. Un spectateur pressé identifie l'auteur à celui qui gagne, ou à celui qui parle bien. Or le théâtre fonctionne exactement à l'inverse. Il donne souvent les meilleures répliques aux êtres les plus contestables, parce qu'un imbécile qui dit une sottise n'apprend rien à personne, tandis qu'un homme intelligent qui défend une position discutable oblige la salle à réfléchir. Le talent d'un dramaturge se mesure à sa capacité de rendre redoutable ce qu'il ne partage pas.

Il faut ajouter que la victoire d'un personnage ne vaut pas approbation. Le théâtre montre ce qui arrive, non ce qui devrait arriver. Qu'un vieux chef rusé l'emporte sur un jeune instituteur sincère ne prouve pas que la ruse vaut mieux que la sincérité : cela prouve que, dans la société représentée, la ruse est plus efficace. Entre le constat et l'éloge, il y a toute la distance qui sépare l'observation du sermon — et c'est dans cette distance que loge la littérature.

On comprend alors pourquoi les pièces à thèse vieillissent si vite. Elles distribuent les rôles à l'avance : voici le bon, voici le méchant, voici la conclusion. Le spectateur n'a plus rien à faire, sinon applaudir ce qu'il pensait déjà. Les œuvres qui durent sont celles qui laissent le travail au public, quitte à le laisser sortir de la salle sans réponse.

Reste une objection sérieuse. À quoi bon un théâtre qui ne tranche pas, dans des sociétés où les questions posées sont urgentes ? Faut-il vraiment tant de nuances pour dire qu'une femme n'est pas une marchandise, ou qu'un peuple a droit à sa terre ? L'objection mérite d'être entendue, et plusieurs auteurs y ont cédé, produisant des œuvres militantes dont l'utilité immédiate fut réelle.

Mais l'expérience suggère que l'efficacité durable est ailleurs. Une pièce qui démontre convainc ceux qui étaient convaincus ; une pièce qui montre atteint aussi les autres, parce qu'elle ne les met pas en accusation. Le spectateur qui a ri d'un personnage se découvre parfois, en rentrant chez lui, qu'il lui ressemblait. Aucun discours n'obtient cela."""
