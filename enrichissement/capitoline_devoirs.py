TEXTE_CONTRACTION = """On répète que l'identité est ce qu'un homme reçoit à sa naissance : une famille, une langue, un village, une communauté. La formule paraît si évidente qu'on ne l'examine plus. Elle mérite pourtant d'être reprise, car elle confond deux choses très différentes : ce qui nous est donné et ce que nous devenons.

Il est vrai qu'un enfant ne choisit ni ses parents ni son lieu de naissance. Mais rien de ce qui fait ensuite son appartenance ne lui est transmis par le sang. Une langue s'apprend, et l'on peut en apprendre plusieurs. Des manières de table, des façons de saluer, des goûts alimentaires s'acquièrent par imitation. Un homme élevé loin des siens ne parlera pas leur langue, ne connaîtra pas leurs plats, ne saura pas leurs formules de politesse. On dira qu'il n'est pas vraiment des leurs : on voudra dire qu'il n'a pas suivi le même apprentissage.

L'objection est connue : il resterait la filiation, qui ne s'apprend pas. Mais la filiation est précisément ce dont personne ne peut être certain, et ceux qui se réclament le plus bruyamment d'une ascendance sont rarement en mesure de la prouver. Il y a là une ironie que les sociétés préfèrent ignorer : l'appartenance la plus revendiquée repose sur la donnée la moins vérifiable.

Ces remarques ne sont pas des jeux d'esprit. Elles ont des conséquences très concrètes, car les groupes qui se croient constitués par nature s'autorisent à exclure ceux qu'ils estiment mal nés. L'exclusion prend alors les formes les plus quotidiennes : une place refusée, un mariage empêché, un terrain qu'on n'accorde pas. Elle ne s'annonce jamais ; elle se manifeste par des lenteurs, des silences, des difficultés qu'on dit traditionnelles et qu'on se garde d'expliquer.

Faut-il conclure qu'il faudrait renoncer à toute appartenance ? Ce serait une autre erreur. Les hommes ont besoin de savoir d'où ils viennent, et les communautés transmettent des biens réels : une langue, une mémoire, des solidarités que rien ne remplace. Le problème n'est pas l'appartenance, il est la prétention à la faire dériver de la naissance plutôt que de l'apprentissage.

Car ce déplacement change tout. Si l'appartenance se reçoit, elle se refuse ; si elle s'apprend, elle s'offre. Une communauté qui se pense comme une école accueille ceux qui veulent y entrer ; une communauté qui se pense comme un lignage n'a rien à leur proposer que la porte."""
